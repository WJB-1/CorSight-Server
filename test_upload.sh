#!/bin/bash
# CorSight 街景图片上传测试脚本
# 测试: POST /api/upload/metadata → POST /api/upload/image

BASE="http://172.23.206.119:5741"

echo "========== 1. 健康检查 =========="
curl -s "$BASE/health" | python -m json.tool 2>/dev/null || curl -s "$BASE/health"
echo ""

echo "========== 2. 创建 metadata session =========="
RESP=$(curl -s -X POST "$BASE/api/upload/metadata" \
  -H "Content-Type: application/json" \
  -d '{
    "point_id": "TEST_POINT_001",
    "location": { "lat": 23.1291, "lng": 113.2644 },
    "crs": "WGS84",
    "images": [
      { "bearing": 0, "fov": 90, "description": "north" },
      { "bearing": 90, "fov": 90, "description": "east" },
      { "bearing": 180, "fov": 90, "description": "south" },
      { "bearing": 270, "fov": 90, "description": "west" }
    ]
  }')
echo "$RESP" | python -m json.tool 2>/dev/null || echo "$RESP"

# 提取 session_id
SESSION_ID=$(echo "$RESP" | python -c "import sys,json; print(json.load(sys.stdin).get('upload_session_id',''))" 2>/dev/null)
echo ""
echo "Session ID: $SESSION_ID"
echo ""

if [ -z "$SESSION_ID" ]; then
  echo "FAIL: 没有获取到 session_id，终止测试"
  exit 1
fi

echo "========== 3. 上传测试图片 =========="
# 生成一个小测试图片（1x1 JPEG）
python -c "
import struct, sys
# 最小合法 JPEG
data = bytes([
    0xFF,0xD8,0xFF,0xE0,0x00,0x10,0x4A,0x46,0x49,0x46,0x00,0x01,
    0x01,0x00,0x00,0x01,0x00,0x01,0x00,0x00,0xFF,0xDB,0x00,0x43,
    0x00,0x08,0x06,0x06,0x07,0x06,0x05,0x08,0x07,0x07,0x07,0x09,
    0x09,0x08,0x0A,0x0C,0x14,0x0D,0x0C,0x0B,0x0B,0x0C,0x19,0x12,
    0x13,0x0F,0x14,0x1D,0x1A,0x1F,0x1E,0x1D,0x1A,0x1C,0x1C,0x20,
    0x24,0x2E,0x27,0x20,0x22,0x2C,0x23,0x1C,0x1C,0x28,0x37,0x29,
    0x2C,0x30,0x31,0x34,0x34,0x34,0x1F,0x27,0x39,0x3D,0x38,0x32,
    0x3C,0x2E,0x33,0x34,0x32,0xFF,0xC0,0x00,0x0B,0x08,0x00,0x01,
    0x00,0x01,0x01,0x01,0x11,0x00,0xFF,0xC4,0x00,0x1F,0x00,0x00,
    0x01,0x05,0x01,0x01,0x01,0x01,0x01,0x01,0x00,0x00,0x00,0x00,
    0x00,0x00,0x00,0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,
    0x09,0x0A,0x0B,0xFF,0xDA,0x00,0x08,0x01,0x01,0x00,0x00,0x3F,
    0x00,0x7B,0x40,0x1B,0xFF,0xD9
])
sys.stdout.buffer.write(data)
" > /tmp/test_upload.jpg

echo "--- 上传 bearing=0 ---"
curl -s -X POST "$BASE/api/upload/image" \
  -F "session_id=$SESSION_ID" \
  -F "bearing=0" \
  -F "image=@/tmp/test_upload.jpg;type=image/jpeg" | python -m json.tool 2>/dev/null

echo "--- 上传 bearing=90 ---"
curl -s -X POST "$BASE/api/upload/image" \
  -F "session_id=$SESSION_ID" \
  -F "bearing=90" \
  -F "image=@/tmp/test_upload.jpg;type=image/jpeg" | python -m json.tool 2>/dev/null

echo ""
echo "========== 4. 查询 session 状态 =========="
curl -s "$BASE/api/upload/session/$SESSION_ID" | python -m json.tool 2>/dev/null

echo ""
echo "========== 测试完成 =========="
